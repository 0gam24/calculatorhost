/** 한국어 법명 → SSoT 키 정규화. */
const NAME_ALIASES = {
  '상증법': '상속세 및 증여세법',
  '상속세및증여세법': '상속세 및 증여세법',
};

export function normalize(name) {
  const trimmed = name.trim();
  return NAME_ALIASES[trimmed] ?? trimmed;
}

// "소득세법 §97의3" / "국세기본법 §47의2" / "상증법 §35 ① 1호" 패턴.
// 의2/의3 같은 부속 번호 포함. ① 같은 항목·호는 검증 대상 아님 (조 번호만 검증).
export const PATTERN =
  /(소득세법(?:\s*시행령)?|국세기본법(?:\s*시행령)?|조세특례제한법|상속세 및 증여세법(?:\s*시행령)?|상증법|지방세법|조세범처벌법)\s*§\s*(\d+(?:의\d+)?)/g;

/**
 * @returns {Array<{filePath: string, lawName: string, articleNum: string,
 *                  reason: 'unregistered' | 'pending-verification' | 'unknown-law'}>}
 *   - unregistered        : 게이트 차단 (신규 hallucination 후보)
 *   - pending-verification: 경고만
 *   - unknown-law         : 레지스트리에 없는 법명 (차단)
 */
export function validateFile(filePath, content) {
  const violations = [];
  let m;
  // JSX 줄바꿈 케이스 (소득세법\n                시행령) 정규화 — 공백·줄바꿈 압축
  const normalized = content.replace(/\s+/g, ' ');
  PATTERN.lastIndex = 0;
  while ((m = PATTERN.exec(normalized)) !== null) {
    const lawName = normalize(m[1]);
    const articleNum = m[2];
    const registry = STATUTE_REGISTRY[lawName];
    if (!registry) {
      violations.push({ filePath, lawName, articleNum, reason: 'unknown-law' });
      continue;
    }
    if (registry.has(articleNum)) continue;
    if (PENDING_VERIFICATION[lawName]?.has(articleNum)) {
      violations.push({ filePath, lawName, articleNum, reason: 'pending-verification' });
      continue;
    }
    violations.push({ filePath, lawName, articleNum, reason: 'unregistered' });
  }
  return violations;
}
